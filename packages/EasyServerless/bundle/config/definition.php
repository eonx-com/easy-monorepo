<?php
declare(strict_types=1);

use Symfony\Component\Config\Definition\Configurator\DefinitionConfigurator;

return static function (DefinitionConfigurator $definition) {
    $definition->rootNode()
        ->children()
            ->arrayNode('app_metric')
                ->canBeDisabled()
                ->children()
                    ->stringNode('namespace')
                        ->defaultNull()
                    ->end()
                ->end()
            ->end()
            ->arrayNode('assets_separate_domain')
                ->canBeDisabled()
                ->children()
                    ->stringNode('url')
                        ->defaultValue('%env(ASSETS_URL)%')
                    ->end()
                ->end()
            ->end()
            ->arrayNode('console')
                ->canBeDisabled()
            ->end()
            ->arrayNode('datadog')
                ->canBeDisabled()
                ->info('Add PHP runtime information to the Datadog root span when the ddtrace extension is loaded.')
            ->end()
            ->arrayNode('easy_error_handler')
                ->setDeprecated(
                    'eonx-com/easy-serverless',
                    '6.15',
                    'The "%node%" option is deprecated and will be removed in 7.0.'
                )
                ->canBeDisabled()
            ->end()
            ->arrayNode('health')
                ->canBeDisabled()
            ->end()
            ->arrayNode('monolog')
                ->canBeDisabled()
            ->end()
            ->arrayNode('sqs')
                ->addDefaultsIfNotSet()
                ->children()
                    ->arrayNode('reset_services')
                        ->canBeDisabled()
                        ->info('Enable resetting Symfony services between serverless message handling.')
                    ->end()
                ->end()
            ->end()
            ->arrayNode('security_headers')
                ->canBeDisabled()
            ->end()
            ->arrayNode('snap_start')
                ->canBeEnabled()
                ->info('Warm the application up before the AWS Lambda SnapStart snapshot and make the restored'
                    . ' execution environments unique. Only active in a remote Lambda initialized by SnapStart.')
                ->children()
                    ->arrayNode('warmers')
                        ->addDefaultsIfNotSet()
                        ->children()
                            ->arrayNode('class_map')
                                ->canBeDisabled()
                                ->info('Load the classes of the namespaces from the Composer class map, it requires'
                                    . ' an optimized autoloader.')
                                ->children()
                                    ->arrayNode('namespaces')
                                        ->stringPrototype()->end()
                                        ->defaultValue(['App\\'])
                                    ->end()
                                ->end()
                            ->end()
                            ->arrayNode('http_request')
                                ->canBeDisabled()
                                ->info('Handle a GET request with the SymfonyHttpHandler, in the functions whose'
                                    . ' handler is the SymfonyHttpHandler.')
                                ->children()
                                    ->stringNode('host')
                                        ->defaultNull()
                                        ->info('Host header of the request, it must be a trusted host when'
                                            . ' "framework.trusted_hosts" is set, e.g. "%env(DOMAIN_API)%".')
                                    ->end()
                                    ->stringNode('path')
                                        ->defaultValue('/easy-serverless/health-check')
                                    ->end()
                                ->end()
                            ->end()
                        ->end()
                    ->end()
                ->end()
            ->end()
            ->arrayNode('state')
                ->canBeDisabled()
                ->children()
                    ->booleanNode('check')
                        ->defaultTrue()
                        ->info('Enable state check after each invocation.')
                    ->end()
                ->end()
        ->end();
};
